export default function sitemap(): MetadataRoute.Sitemap {
  return (["en", "zh"] as const).flatMap((lang) => routes.map((route) => ({
    url: `${base}/${lang}${route ? `/${route}` : ""}`,
    changeFrequency: route.startsWith("events") ? "weekly" as const : "monthly" as const,
    priority: route === "" ? 1 : route === "events" || route === "activities" ? 0.9 : 0.7,
    alternates: {
      languages: {
        en: `${base}/en${route ? `/${route}` : ""}`,
        "zh-Hant": `${base}/zh${route ? `/${route}` : ""}`,
      },
    },
  })));
}
